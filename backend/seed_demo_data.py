def seed(email: str) -> int:
    create_tables()
    db = SessionLocal()
    try:
        user = db.query(User).filter(func.lower(User.email) == email.strip().lower()).first()
        if user is None:
            raise ValueError(f"No StepWise account was found for {email!r}.")
        created = 0
        for sample in SAMPLES:
            conversation = (db.query(Conversation)
                            .filter(Conversation.user_id == user.id, Conversation.title == sample["title"])
                            .first())
            if conversation:
                continue
            conversation = Conversation(user_id=user.id, title=sample["title"], subject=sample["subject"],
                                        frustration_score=sample["support"], consecutive_loops=sample.get("loops", 1))
            db.add(conversation)
            db.flush()
            parent_id = None
            source_message_id = None
            last_user_message_id = None
            for user_text, tutor_text in sample["turns"]:
                user_message = Message(conversation_id=conversation.id, role="user", content=user_text,
                                       parent_message_id=parent_id)
                db.add(user_message)
                db.flush()
                source_message_id = user_message.id
                last_user_message_id = user_message.id
                tutor_message = Message(conversation_id=conversation.id, role="assistant", content=tutor_text,
                                        parent_message_id=user_message.id)
                db.add(tutor_message)
                db.flush()
                parent_id = tutor_message.id
            if sample.get("alternate_tutor_reply"):
                db.add(Message(conversation_id=conversation.id, role="assistant",
                               content=sample["alternate_tutor_reply"], parent_message_id=last_user_message_id))
            if sample.get("category"):
                db.add(MisconceptionLog(user_id=user.id, conversation_id=conversation.id,
                                        source_message_id=source_message_id, category_code=sample["category"],
                                        confidence=sample["confidence"], is_sample=True))
            created += 1
        db.commit()
        return created
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--email", required=True, help="Email of the local StepWise account to receive demo data")
    args = parser.parse_args()
    count = seed(args.email)
    print(f"Added {count} sample conversations. Existing samples were left unchanged.")
